#!/usr/bin/env node
/**
 * Generates the Supabase schema for the shared demo sandbox from the Base44
 * entity files, so the two never drift:
 *   base44/entities/BotRun.jsonc      → public.bot_runs
 *   base44/entities/Trade.jsonc       → public.trades
 *   base44/entities/WhaleSignal.jsonc → public.whale_signals
 *
 * Output: supabase/migrations/20261028000000_demo_sandbox.sql
 * Run with `npm run supabase:schema` after changing an entity.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'supabase', 'migrations', '20261028000000_demo_sandbox.sql');

const ENTITIES = [
  { file: 'BotRun.jsonc', table: 'bot_runs' },
  { file: 'Trade.jsonc', table: 'trades' },
  { file: 'WhaleSignal.jsonc', table: 'whale_signals' },
];

const readJsonc = path =>
  JSON.parse(
    readFileSync(path, 'utf8')
      .split('\n')
      .filter(line => !line.trim().startsWith('//'))
      .join('\n')
  );

function sqlType(prop) {
  if (prop.type === 'number' || prop.type === 'integer') return 'double precision';
  if (prop.type === 'boolean') return 'boolean';
  if (prop.type === 'array' || prop.type === 'object') return 'jsonb';
  if (prop.type === 'string' && prop.format === 'date-time') return 'timestamptz';
  return 'text';
}

function tableSql({ file, table }) {
  const schema = readJsonc(join(root, 'base44', 'entities', file));
  const cols = Object.entries(schema.properties).map(([name, prop]) => {
    const def = prop.default !== undefined ? ` default ${typeof prop.default === 'string' ? `'${prop.default}'` : JSON.stringify(prop.default)}` : '';
    const comment = prop.description ? ` -- ${prop.description.replace(/\s+/g, ' ')}` : '';
    return `  "${name}" ${sqlType(prop)}${def},${comment}`;
  });
  return `create table if not exists public.${table} (
  "id" uuid primary key default gen_random_uuid(),
  "created_date" timestamptz not null default now(),
  "updated_date" timestamptz not null default now(),
  "created_by" text,
${cols.join('\n')}
  "_" boolean -- trailing column keeps the generated list simple; unused
);
alter table public.${table} drop column if exists "_";
create trigger ${table}_updated before update on public.${table} for each row execute function public.set_updated_date();
`;
}

const header = `-- Shared demo sandbox for PolyBot Terminal. Generated by scripts/gen-supabase-schema.mjs
-- from base44/entities/*.jsonc. Edit the entity files and rerun; hand-written parts are
-- below the generated tables.

create extension if not exists pgcrypto;

create or replace function public.set_updated_date() returns trigger language plpgsql as $$
begin
  new.updated_date := now();
  return new;
end $$;

`;

const tail = `
-- ─── Indexes ────────────────────────────────────────────────────────────────
create index if not exists bot_runs_status_idx on public.bot_runs ("status");
create index if not exists bot_runs_created_idx on public.bot_runs ("created_date" desc);
create index if not exists trades_bot_status_idx on public.trades ("bot_run_id", "status");
create index if not exists trades_created_idx on public.trades ("created_date" desc);
create unique index if not exists whale_signals_trade_idx on public.whale_signals ("trade_id");
create index if not exists whale_signals_traded_idx on public.whale_signals ("traded_at" desc);

-- ─── Sandbox metadata (one row) ─────────────────────────────────────────────
create table if not exists public.demo_meta (
  id int primary key,
  created_at timestamptz not null default now(),
  last_reset_at timestamptz not null default now(),
  resets_at timestamptz not null default now() + interval '2 hours',
  reset_every interval not null default interval '2 hours',
  last_tick_at timestamptz
);
insert into public.demo_meta (id) values (1) on conflict (id) do nothing;

-- ─── Guard rails for a public sandbox ───────────────────────────────────────
-- Anyone can start a paper portfolio. Keep it small: 20 active portfolios at a time,
-- paper amounts between $1 and $10,000, short names.
create or replace function public.bot_runs_guard() returns trigger language plpgsql as $$
declare active_count int;
begin
  select count(*) into active_count from public.bot_runs where "status" in ('running', 'paused');
  if active_count >= 20 then
    raise exception 'The sandbox is full (20 running portfolios). It resets on the next schedule.';
  end if;
  if new."fund_allocation" is null or new."fund_allocation" < 1 or new."fund_allocation" > 10000 then
    raise exception 'Paper amounts in the sandbox are between $1 and $10,000.';
  end if;
  if new."is_paper" is distinct from true then
    new."is_paper" := true;
    new."fill_mode" := 'paper';
  end if;
  new."name" := left(coalesce(new."name", 'portfolio'), 60);
  return new;
end $$;
drop trigger if exists bot_runs_guard on public.bot_runs;
create trigger bot_runs_guard before insert on public.bot_runs for each row execute function public.bot_runs_guard();

-- ─── Reset: wipe everything, the next tick re-seeds the sample portfolios ───
create or replace function public.demo_reset() returns void language plpgsql security definer set search_path = public as $$
begin
  truncate table public.trades, public.bot_runs;
  update public.demo_meta set last_reset_at = now(), resets_at = now() + reset_every where id = 1;
end $$;
revoke all on function public.demo_reset() from public, anon, authenticated;

-- ─── Row-level security: the browser (anon key) reads, creates and updates; never deletes ──
alter table public.bot_runs enable row level security;
alter table public.trades enable row level security;
alter table public.whale_signals enable row level security;
alter table public.demo_meta enable row level security;

drop policy if exists "sandbox read" on public.bot_runs;
drop policy if exists "sandbox insert" on public.bot_runs;
drop policy if exists "sandbox update" on public.bot_runs;
create policy "sandbox read" on public.bot_runs for select to anon, authenticated using (true);
create policy "sandbox insert" on public.bot_runs for insert to anon, authenticated with check (true);
create policy "sandbox update" on public.bot_runs for update to anon, authenticated using (true) with check (true);

drop policy if exists "sandbox read" on public.trades;
drop policy if exists "sandbox insert" on public.trades;
drop policy if exists "sandbox update" on public.trades;
create policy "sandbox read" on public.trades for select to anon, authenticated using (true);
create policy "sandbox insert" on public.trades for insert to anon, authenticated with check (true);
create policy "sandbox update" on public.trades for update to anon, authenticated using (true) with check (true);

drop policy if exists "signals read" on public.whale_signals;
create policy "signals read" on public.whale_signals for select to anon, authenticated using (true);

drop policy if exists "meta read" on public.demo_meta;
create policy "meta read" on public.demo_meta for select to anon, authenticated using (true);

grant usage on schema public to anon, authenticated;
grant select, insert, update on public.bot_runs, public.trades to anon, authenticated;
grant select on public.whale_signals, public.demo_meta to anon, authenticated;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, header + ENTITIES.map(tableSql).join('\n') + tail);
console.log(`wrote ${OUT.replace(root + '/', '')}`);
